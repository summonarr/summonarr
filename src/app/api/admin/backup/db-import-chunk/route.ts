import { NextResponse } from "next/server";
import { withAdmin } from "@/lib/api-auth";
import { checkBodySize, readBodyBytesCapped } from "@/lib/body-size";
import { checkRateLimit } from "@/lib/rate-limit";
import {
  processBackupImport,
  MAX_CIPHERTEXT_BYTES,
} from "@/lib/backup-import";
import {
  startSession,
  appendChunk,
  getSessionStream,
  clearSession,
  cancelSession,
  type AppendError,
  type SessionStartError,
} from "@/lib/import-session";
import { translatorForRequest } from "@/lib/i18n/server-locale";
import type { Translator } from "@/lib/i18n/translate";
import { parseUploadChunkHeaders } from "@/lib/upload-chunk-headers";
import { auditAdminImport, backupPasswordOrResponse, importResultResponse } from "@/lib/backup-routes";

// Per-chunk size cap, the same as the sibling /api/setup/import-chunk route.
// Without it, one huge chunk could run the server out of memory (OOM) while it is
// read in. MUST stay below next.config.ts proxyClientMaxBodySize, which TRUNCATES
// a longer body instead of refusing it (see the sibling route).
const MAX_CHUNK_BYTES = 20 * 1024 * 1024;

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

const mb = (bytes: number) => Math.round(bytes / (1024 * 1024));

// Why chunk 0 could not open the upload, as the answer.
function startFailure(e: SessionStartError, t: Translator): NextResponse {
  if (e.kind === "in-progress") {
    return NextResponse.json({ error: t("apiAdmin.backup.uploadInProgress") }, { status: 409 });
  }
  if (e.kind === "size-too-large") {
    return NextResponse.json({ error: t("apiAdmin.backup.fileTooLarge", { mb: mb(e.max) }) }, { status: 413 });
  }
  return NextResponse.json({ error: t("apiAdmin.backup.invalidUploadParams") }, { status: 400 });
}

// Why a chunk could not be appended, as the answer.
function appendFailure(e: AppendError, t: Translator): NextResponse {
  switch (e.kind) {
    case "no-session":
      return NextResponse.json({ error: t("apiAdmin.backup.noUploadSession") }, { status: 409 });
    case "session-mismatch":
      return NextResponse.json({ error: t("apiAdmin.backup.uploadIdMismatch") }, { status: 409 });
    case "expired":
      return NextResponse.json({ error: t("apiAdmin.backup.uploadExpired") }, { status: 410 });
    case "out-of-order":
      // `expected` lets a retrying uploader tell "my earlier attempt landed"
      // (expected === its index + 1) from a real ordering error.
      return NextResponse.json({ error: t("apiAdmin.backup.outOfOrder", { expected: e.expected }), expected: e.expected }, { status: 409 });
    case "size-mismatch":
      return NextResponse.json({ error: t("apiAdmin.backup.incomplete", { received: e.received, expected: e.expected }) }, { status: 400 });
    case "size-overflow":
      return NextResponse.json({ error: t("apiAdmin.backup.chunkExceedsDeclared") }, { status: 413 });
  }
}

// POST: append a chunk. Final chunk runs the import.
//
// Headers (matches /api/setup/import-chunk; parsed by parseUploadChunkHeaders):
//   X-Upload-Id     UUID v4 generated by the client
//   X-Chunk-Index   0-based index of this chunk
//   X-Chunk-Total   total chunks
//   X-File-Size     total file size in bytes
// A header that is absent or not a whole number is a 400 before any upload
// work — a missing index used to read as chunk 0 and restart the upload.
export const POST = withAdmin(async (req, _ctx, session) => {
  const t = translatorForRequest(req);
  const pw = backupPasswordOrResponse(t, "admin");
  if (pw instanceof NextResponse) return pw;
  const { password } = pw;

  const headers = parseUploadChunkHeaders(req.headers);
  if (!headers) {
    return NextResponse.json({ error: t("apiAdmin.backup.invalidUploadHeaders") }, { status: 400 });
  }
  const { uploadId, chunkIndex, chunkTotal, fileSize } = headers;
  if (fileSize > MAX_CIPHERTEXT_BYTES) {
    return NextResponse.json({ error: t("apiAdmin.backup.fileTooLarge", { mb: mb(MAX_CIPHERTEXT_BYTES) }) }, { status: 413 });
  }

  if (!req.body) {
    return NextResponse.json({ error: t("apiAdmin.backup.emptyChunk") }, { status: 400 });
  }

  // Rate-limit the restore *attempt*, not each chunk: consume one slot when the
  // client opens the session (chunk 0). A real backup is split into many 16 MiB
  // chunks, so a per-chunk limiter would burn the bucket and 429 the restore
  // partway through. Bounds how often a compromised admin can drive the
  // destructive TRUNCATE+INSERT / PBKDF2 import.
  if (chunkIndex === 0 && !checkRateLimit(`admin-db-import:${session.user.id}`, 5, 60 * 60 * 1000)) {
    return NextResponse.json({ error: t("apiAdmin.backup.tooManyRestores") }, { status: 429 });
  }

  // Header-only size check BEFORE claiming the single upload slot. startSession()
  // mkdtemps a temp dir and occupies the one global slot; an oversized chunk 0 that
  // bailed after it would strand that slot (409 for everyone else) until the 30-min TTL.
  const sizeCheck = checkBodySize(req, MAX_CHUNK_BYTES);
  if (sizeCheck) return sizeCheck;

  if (chunkIndex === 0) {
    const start = await startSession({ uploadId, totalSize: fileSize, totalChunks: chunkTotal });
    if (!start.ok) return startFailure(start.error, t);
  }

  const chunkBytes = await readBodyBytesCapped(req, MAX_CHUNK_BYTES);
  if (chunkBytes === null) {
    // Belt-and-suspenders for transfer-encoding: chunked uploads where the
    // Content-Length-based check above can't trigger; the read stops at the cap.
    // An oversized chunk corrupts the upload, so release the slot for ANY index
    // (not just chunk 0) — otherwise an oversized non-zero chunk strands the
    // global slot until its TTL.
    await clearSession(uploadId);
    return NextResponse.json({ error: t("apiAdmin.backup.chunkTooLarge", { mb: mb(MAX_CHUNK_BYTES) }) }, { status: 413 });
  }
  const append = await appendChunk(uploadId, chunkIndex, chunkBytes);
  if (!append.ok) return appendFailure(append.error, t);

  if (!append.complete) {
    return NextResponse.json({
      ok: true,
      received: append.received,
      total: append.total,
      bytesWritten: append.bytesWritten,
      complete: false,
    });
  }

  const stream = getSessionStream(uploadId);
  if (!stream) {
    await clearSession(uploadId);
    return NextResponse.json({ error: t("apiAdmin.backup.uploadStateLost") }, { status: 500 });
  }

  let result;
  try {
    result = await processBackupImport(stream, password);
  } finally {
    await clearSession(uploadId);
  }

  // Audited whether or not it succeeded — after the restore, never inside it
  // (guardrail 26). Every rejection above happened before the import and is not.
  auditAdminImport(req, session, result, "admin-chunked");
  return importResultResponse(result, t, { chunked: true });
});

// DELETE: cancel the in-flight upload. Always 200 (the uploader ignores the
// answer). A session already being imported is left alone: the uploader cancels
// when the final chunk's request fails at a proxy while the restore still runs,
// and the importer frees the slot itself when it ends.
export const DELETE = withAdmin(async (req, _ctx, _session) => {
  const t = translatorForRequest(req);
  const uploadId = req.headers.get("x-upload-id") ?? "";
  if (!uploadId) {
    return NextResponse.json({ error: t("apiAdmin.backup.missingUploadId") }, { status: 400 });
  }
  await cancelSession(uploadId);
  return NextResponse.json({ ok: true });
});
