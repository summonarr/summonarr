import { NextRequest, NextResponse } from "next/server";
import { checkRateLimit, getClientIpKey } from "@/lib/rate-limit";
import { checkBodySize, readBodyBytesCapped } from "@/lib/body-size";
import {
  processBackupImport,
  MAX_CIPHERTEXT_BYTES,
} from "@/lib/backup-import";
import {
  startSession,
  appendChunk,
  getSessionStream,
  clearSession,
  cancelSession,
  hasActiveUploadSession,
  type AppendError,
  type SessionStartError,
} from "@/lib/import-session";
import { translatorForRequest } from "@/lib/i18n/server-locale";
import type { Translator } from "@/lib/i18n/translate";
import { parseUploadChunkHeaders } from "@/lib/upload-chunk-headers";
import { auditSetupImport, importResultResponse, setupRestoreGate } from "@/lib/backup-routes";

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

// Client uploader defaults to 16 MiB chunks; cap at 20 MiB to leave headroom while
// still bounding memory. MUST stay below next.config.ts proxyClientMaxBodySize, which
// TRUNCATES a longer body instead of refusing it: a cut-off chunk has to arrive
// over this cap and be refused, never fit under it and be appended corrupt.
const MAX_CHUNK_BYTES = 20 * 1024 * 1024;

// POST: append a chunk. On the final chunk, run the import.
//
// Headers (shared with /api/admin/backup/db-import-chunk; parsed by
// parseUploadChunkHeaders):
//   X-Upload-Id     UUID v4 generated by the client
//   X-Chunk-Index   0-based index of this chunk
//   X-Chunk-Total   total chunks in the upload
//   X-File-Size     total file size in bytes
// Body: raw chunk bytes (application/octet-stream)
export async function POST(req: NextRequest) {
  const t = translatorForRequest(req);
  // An absent or empty header, or anything but plain digits, is a 400 before
  // the rate limit and any session work: Number("") is 0, so a request with no
  // X-Chunk-Index used to read as chunk 0, spend the attempt and start a session.
  const headers = parseUploadChunkHeaders(req.headers);
  if (!headers) {
    return NextResponse.json({ error: t("apiAuth.setup.badHeaders") }, { status: 400 });
  }
  const { uploadId, chunkIndex, chunkTotal, fileSize } = headers;

  // Rate-limit the upload *attempt*, not each chunk: consume one slot when the client
  // opens the session (chunk 0). A real backup is split into many 16 MiB chunks, so a
  // per-chunk limiter would burn the whole bucket and 429 the restore partway through.
  if (chunkIndex === 0 && !checkRateLimit(`setup-import:${getClientIpKey(req.headers)}`, 5, 5 * 60 * 1000)) {
    return NextResponse.json({ error: t("apiAuth.setup.tooManyAttempts") }, { status: 429 });
  }

  // A non-zero chunk with no matching active session is bogus (no rate-limited
  // chunk-0 opened it). Reject it HERE, before the setup gate takes advisory lock
  // 43 and runs DB reads — otherwise an unauthenticated flood of junk chunk-N
  // requests skips the chunk-0 limiter yet amplifies into advisory-lock contention
  // (shared with /api/auth/register) and DB load. Legit chunk-N always has a session.
  if (chunkIndex !== 0 && !hasActiveUploadSession(uploadId)) {
    return NextResponse.json({ error: t("apiAuth.setup.noSession") }, { status: 409 });
  }

  const sizeCheck = checkBodySize(req, MAX_CHUNK_BYTES);
  if (sizeCheck) return sizeCheck;

  // The internet-facing opt-in, freshness under lock 43, and the password —
  // shared with /api/setup/import (backup-routes.ts). At every chunk, so a
  // registration that lands mid-upload stops it.
  const g = await setupRestoreGate(t);
  if (g instanceof NextResponse) return g;
  if ("closed" in g) {
    // Setup completed (or a user appeared) mid-upload. Free the single global
    // slot this uploadId holds so a subsequent legitimate restore isn't blocked
    // by a stale in-flight session until its TTL.
    await clearSession(uploadId);
    return NextResponse.json(
      { error: t("apiAuth.setup.notFresh") },
      { status: 409 },
    );
  }
  const { password } = g;

  if (fileSize > MAX_CIPHERTEXT_BYTES) {
    return NextResponse.json(
      { error: t("apiAuth.setup.fileTooLarge", { mb: Math.round(MAX_CIPHERTEXT_BYTES / (1024 * 1024)) }) },
      { status: 413 },
    );
  }

  // Before startSession, as the admin twin orders it: a body-less chunk 0 used
  // to claim the single global upload slot and then 400 without releasing it,
  // so the operator's real first-run restore 409'd "in progress" for up to the
  // 10-minute idle TTL.
  if (!req.body) {
    return NextResponse.json({ error: t("apiAuth.setup.emptyChunk") }, { status: 400 });
  }

  if (chunkIndex === 0) {
    const start = await startSession({ uploadId, totalSize: fileSize, totalChunks: chunkTotal });
    if (!start.ok) return startRefusal(start.error, t);
  }

  // Capped read for Transfer-Encoding: chunked uploads, where checkBodySize's
  // Content-Length check above can't fire (mirrors db-import-chunk). It stops at
  // the cap instead of buffering the whole body first: this route is
  // unauthenticated while the first-run gate is open.
  const chunkBytes = await readBodyBytesCapped(req, MAX_CHUNK_BYTES);
  if (chunkBytes === null) {
    // An oversized chunk corrupts the upload — release the slot for ANY index
    // (not just chunk 0) so it isn't stranded until the session TTL.
    await clearSession(uploadId);
    return NextResponse.json(
      { error: t("apiAuth.setup.chunkTooLarge", { mb: Math.round(MAX_CHUNK_BYTES / (1024 * 1024)) }) },
      { status: 413 },
    );
  }
  const append = await appendChunk(uploadId, chunkIndex, chunkBytes);
  if (!append.ok) return appendRefusal(append.error, t);

  if (!append.complete) {
    return NextResponse.json({
      ok: true,
      received: append.received,
      total: append.total,
      bytesWritten: append.bytesWritten,
      complete: false,
    });
  }

  const stream = getSessionStream(uploadId);
  if (!stream) {
    await clearSession(uploadId);
    return NextResponse.json({ error: t("apiAuth.setup.stateLost") }, { status: 500 });
  }

  let result;
  try {
    result = await processBackupImport(stream, password, "setup");
  } finally {
    await clearSession(uploadId);
  }

  if (result.ok) await auditSetupImport(req, result, "setup-chunked");
  return importResultResponse(result, t, { chunked: true });
}

// The answer to a chunk 0 that could not open the upload session.
function startRefusal(e: SessionStartError, t: Translator): NextResponse {
  if (e.kind === "in-progress") {
    return NextResponse.json({ error: t("apiAuth.setup.inProgress") }, { status: 409 });
  }
  if (e.kind === "size-too-large") {
    return NextResponse.json(
      { error: t("apiAuth.setup.fileTooLarge", { mb: Math.round(e.max / (1024 * 1024)) }) },
      { status: 413 },
    );
  }
  return NextResponse.json({ error: t("apiAuth.setup.badParams") }, { status: 400 });
}

// The answer to a chunk the upload session refused.
function appendRefusal(e: AppendError, t: Translator): NextResponse {
  switch (e.kind) {
    case "no-session":
      return NextResponse.json({ error: t("apiAuth.setup.noSession") }, { status: 409 });
    case "session-mismatch":
      return NextResponse.json({ error: t("apiAuth.setup.sessionMismatch") }, { status: 409 });
    case "expired":
      return NextResponse.json({ error: t("apiAuth.setup.sessionExpired") }, { status: 410 });
    case "out-of-order":
      // `expected` lets a retrying uploader tell "my earlier attempt landed"
      // (expected === its index + 1) from a real ordering error.
      return NextResponse.json(
        { error: t("apiAuth.setup.outOfOrder", { expected: e.expected }), expected: e.expected },
        { status: 409 },
      );
    case "size-mismatch":
      return NextResponse.json(
        { error: t("apiAuth.setup.incomplete", { received: e.received, expected: e.expected }) },
        { status: 400 },
      );
    case "size-overflow":
      return NextResponse.json({ error: t("apiAuth.setup.chunkExceedsSize") }, { status: 413 });
  }
}

// DELETE: cancel the in-flight upload and remove the temp file.
export async function DELETE(req: NextRequest) {
  const t = translatorForRequest(req);
  const uploadId = req.headers.get("x-upload-id") ?? "";
  if (!uploadId) {
    return NextResponse.json({ error: t("apiAuth.setup.missingUploadId") }, { status: 400 });
  }
  // Cancel only releases the in-memory upload slot + temp file for this
  // uploadId (no DB mutation), and is a no-op unless this uploadId owns the
  // active session — or while that session's file is being imported (the
  // importer frees it when the restore ends). It must always succeed so a
  // stale slot can be freed even after setup has closed or backup config changed.
  await cancelSession(uploadId);
  return NextResponse.json({ ok: true });
}
